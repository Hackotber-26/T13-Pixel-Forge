type Lang = 'en' | 'hi'
const dicts = { en, hi }
// `alt` is the other language: main buttons carry both, the way Indian signage does.
const LangContext = createContext<{ t: Dict; alt: Dict; lang: Lang; toggle: () => void }>({ t: en, alt: hi, lang: 'en', toggle: () => {} })

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>(() => {
    try { return (localStorage.getItem('raksha.lang') as Lang) || 'en' } catch { return 'en' }
  })
  const toggle = () => {
    const next = lang === 'en' ? 'hi' : 'en'
    setLang(next)
    try { localStorage.setItem('raksha.lang', next) } catch { /* ignore */ }
    document.documentElement.lang = next
  }
  return <LangContext.Provider value={{ t: dicts[lang], alt: dicts[lang === 'en' ? 'hi' : 'en'], lang, toggle }}>{children}</LangContext.Provider>
}

export const useT = () => useContext(LangContext)
